from pydantic import BaseModel, Field
from typing import Annotated, Literal
from operator import add

class AgentState(BaseModel):
    messages: Annotated[list,add] = Field(..., description='List of messages to be processed by the agent')   # this the prompt given by the user.
    user_question:str = Field(...,description="The original Question asked by the user")
    curated_que : str = Field(...,description="Curated question to be answered by the agent.")                # currated question given by the LLM model after restructuring the user message.
    prompt_context_query : str = Field(...,description="Context for the prompt query")
    is_safe : Literal ["Yes","No"] = Field(...,description="Indicates whether the query generated by LLM is safe to perform against the database is safe or not.")
    generated_sql_query : str = Field(...,description="The SQL query generated by the agent based on the cuarted question and prompt context")
    sql_query_execution_result :str = Field(..., description="The result of executing the generated SQL query on the database.")
    final_answer :str = Field(..., description="The final answer generated by the agent based on prompt.")
    comments : str = Field(...,description="Additional Comments or feedback provided by the agent regarding the safety of the query generated by LLM.")

class judgeSchema(BaseModel):
    answer: Literal ["Yes","No"] = Field(...,description="Indicates whether the query generated by LLM is safe to perform against the database is safe or not.")
    comments: str = Field(...,description="Additional Comments or feedback provided by the agent regarding the safety of the query generated by LLM.")


class ETLSchema(BaseModel):
    messages: Annotated[list,add] = Field(..., description='List of messages to be processed by the ETL agent')   # this the prompt given by the user.


